def asistencia_dispersion():
    """
    La asistencia a los 10 últimos partidos en casa de las Águilas de Baltimore fue la siguiente:

    [20100, 24500, 31600, 28400, 49500, 19350, 25600, 30600, 11300, 28560]

    Calcule el rango, la varianza y la desviación stándard para estos datos
    Regrese una tupla con el siguiente orden, como se muestra a continuación:
    """
    asistenciaAguilasBal = np.array([20100, 24500, 31600, 28400, 49500, 19350, 25600, 30600, 11300, 28560])
    rango = np.max(asistenciaAguilasBal) - np.min(asistenciaAguilasBal)
    varianza = np.var(asistenciaAguilasBal)
    desv_est = np.std(asistenciaAguilasBal)
    return (rango, varianza, desv_est)

asistencia_dispersion()

